export const dictionaries: Record<Lang, Record<MessageKey, string>> = { es, pt };

export type Translate = (key: MessageKey) => string;

export interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
  /** Traduz um valor vindo da API (ex.: "Approved", "Cuenta Corriente") usando um prefixo; se não houver tradução, devolve o valor. */
  tv: (prefix: 'status' | 'statusText' | 'reason' | 'type' | 'cat' | 'product' | 'method' | 'sch.st', value: string | null | undefined) => string;
}

export function makeI18n(lang: Lang, setLang: (lang: Lang) => void): I18n {
  const dict = dictionaries[lang];
  return {
    lang,
    setLang,
    t: (key) => dict[key] ?? key,
    tv: (prefix, value) => (value ? (dict[`${prefix}.${value}` as MessageKey] ?? value) : '—'),
  };
}

export const I18nContext = createContext<I18n>(makeI18n('es', () => {}));
export const useI18n = () => useContext(I18nContext);

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('banco-latam-lang');
    if (saved === 'es' || saved === 'pt') return saved;
  } catch {
    /* sem storage */
  }
  return navigator.language?.toLowerCase().startsWith('pt') ? 'pt' : 'es';
}

export function persistLang(lang: Lang) {
  try {
    localStorage.setItem('banco-latam-lang', lang);
  } catch {
    /* sem storage */
  }
}
